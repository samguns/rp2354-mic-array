"""Reproducible stdlib-only 48 kHz PDM decimator coefficient generation."""
import math,json
from pathlib import Path

def i0(x):
 total=term=1.0
 for k in range(1,80):
  term*=x*x/(4*k*k);total+=term
  if term<total*1e-16:break
 return total

def lowpass(n,cutoff,beta):
 mid=(n-1)/2;out=[]
 for k in range(n):
  t=k-mid
  value=2*cutoff if t==0 else math.sin(2*math.pi*cutoff*t)/(math.pi*t)
  value*=i0(beta*math.sqrt(max(0,1-(t/mid)**2)))/i0(beta)
  out.append(value)
 scale=sum(out);return [v/scale for v in out]

half=lowpass(31,.25,8.6)
for n in range(31):
 if n%2 and n!=15:half[n]=0
half=[x/sum(half) for x in half]
final=lowpass(63,.25,8.6)
for n in range(63):
 if n%2 and n!=31:final[n]=0
final=[x/sum(final) for x in final]
comp=[-.02,1.04,-.02]
root=Path(__file__).resolve().parents[1]
text='/* Generated by tools/design_pdm48.py; unity DC gain. */\n'
for name,values in [('pdm_halfband',half),('pdm_final',final),('pdm_comp',comp)]:
 quantized=[round(x*16384) for x in values];quantized[len(values)//2]+=16384-sum(quantized)
 # A leading zero pads the reversed-time dot product to an even tap count.
 assert sum(abs(x) for x in quantized)*32768+8192 < 2**31
 if name!='pdm_comp':quantized=[0]+quantized
 text+='static const int16_t '+name+'['+str(len(quantized))+'] = {\n'
 text+='\n'.join(' '+', '.join(str(x) for x in quantized[i:i+8])+',' for i in range(0,len(quantized),8))+'\n};\n'
(root/'src/pdm_coefficients.h').write_text(text,encoding='utf-8')
(root/'build-tests/pdm48-coefficients.json').write_text(json.dumps(dict(halfband=half,final=final),indent=2))
print('Generated CIC4/16 -> halfband/2 -> compensated FIR/2 coefficients')
