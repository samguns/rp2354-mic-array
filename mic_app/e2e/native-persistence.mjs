// Real packaged-app suppression and flash persistence workflow.
import {chromium,expect} from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.connectOverCDP('http://127.0.0.1:9222');
const page=browser.contexts().flatMap(c=>c.pages()).find(p=>!p.url().startsWith('devtools:'));
if(!page)throw new Error('Test WebView missing');
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.getByRole('button',{name:'Connect board',exact:true}).click();
await expect(page.locator('.mode-pill')).toHaveText('DEVICE',{timeout:10000});
await expect(page.getByRole('button',{name:'Disable suppression',exact:true})).toBeEnabled({timeout:10000});
await page.getByRole('button',{name:'Disable suppression',exact:true}).click();
await expect(page.locator('.noise-settings')).toContainText('Off',{timeout:10000});
await page.getByRole('button',{name:'Enable suppression',exact:true}).click();
await expect(page.locator('.noise-settings')).toContainText('Enabled',{timeout:10000});
await page.getByRole('button',{name:'Relearn noise',exact:true}).click();
await expect(page.getByRole('button',{name:'Relearn noise',exact:true})).toBeDisabled({timeout:4000});
await expect(page.getByRole('button',{name:'Relearn noise',exact:true})).toBeEnabled({timeout:10000});
await expect(page.getByRole('button',{name:'Save & restart',exact:true})).toBeEnabled({timeout:10000});
await page.getByRole('button',{name:'Save & restart',exact:true}).click();
await expect(page.locator('.mode-pill')).toHaveText('DISCONNECTED',{timeout:10000});
await expect(page.locator('.mode-pill')).toHaveText('DEVICE',{timeout:15000});
await expect(page.locator('.persistence')).toContainText('Audio settings saved on board',{timeout:10000});
await expect(page.locator('.noise-settings')).toContainText('Enabled');
await expect(page.locator('.beam-controls')).toContainText('Learned');
await page.screenshot({path:'../build-tests/persistent-audio/native-settings.png',fullPage:true});
await page.getByRole('button',{name:'Disconnect',exact:true}).click();
await fs.writeFile('../build-tests/persistent-audio/native-settings.json',JSON.stringify({result:'PASS',errors,checks:['disable suppression','enable suppression','learn noise','save and restart','automatic reconnect','saved mode and profile restored']},null,2));
if(errors.length)throw new Error(errors.join('\n'));
console.log('Native suppression and persistence workflow passed.');await browser.close();
